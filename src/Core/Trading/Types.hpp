#ifndef TYPES_HPP
#define TYPES_HPP
#include <string>

namespace Core::Trading
{

// Одна свеча в числовом виде. Конвертируется из Kline один раз на входе в стратегию.
struct Bar
{
    int64_t start = 0;    // время открытия свечи, Unix-время в мс (UTC); первый элемент свечи в ответе Bybit
    double open = 0;     // цена первой сделки свечи
    double high = 0;     // максимальная цена за свечу
    double low = 0;      // минимальная цена за свечу
    double close = 0;    // цена последней сделки; у закрытой свечи не меняется
    double volume = 0;   // объём в базовой монете (для BTCUSDT это BTC)
};

// Направление позиции.
enum class SideType
{
    None,    // позиции нет
    Long,    // ставка на рост: купили, прибыль при росте цены
    Short    // ставка на падение: продали, прибыль при падении цены (только фьючерсы)
};

// Состояние сделки. Ведёт его движок или симулятор по фактическим исполнениям,
// стратегия только читает.
struct Position
{
    SideType side = SideType::None;  // направление; None означает, что остальные поля не используются
    double entry = 0;     // средневзвешенная цена входа (при частичных исполнениях это среднее)
    double qty = 0;       // размер позиции в базовой монете; всегда положительный, направление задаёт side
    double stop = 0;      // текущий уровень защитного стопа (цена); 0 = стоп не задан
    double highest = 0;   // максимальный high с момента входа, по свечам ДО текущей; для трейлинга лонга
    double lowest = 0;    // минимальный low с момента входа, по свечам ДО текущей; для трейлинга шорта
    int barsHeld = 0;     // сколько закрытых свечей позиция уже открыта; для выхода по времени
    bool open() const { return side != SideType::None; }
};

// Всё, что стратегия получает на каждой закрытой свече.
struct Context
{
    Bar bar;              // только что закрытая свеча
    Position pos;         // состояние позиции на момент ДО обработки этой свечи
    double equity = 0;    // капитал счёта в котируемой валюте (USDT); база для расчёта риска и размера
};

// Что стратегия просит сделать.
enum class SignalType
{
    None,       // ничего не делать (в reason может быть причина пропуска, например "Skip: ...")
    OpenLong,   // открыть лонг
    OpenShort,  // открыть шорт
    Close       // закрыть текущую позицию целиком
};

struct Signal
{
    SignalType type = SignalType::None;  // действие
    double qty = 0;       // сколько открыть (Buy/Sell) или закрыть (Close), в базовой монете
    double stop = 0;      // цена защитного стопа для нового входа; для Close и None не используется (0)
    std::string reason;   // текст для журнала сигналов: почему вошли, вышли или пропустили
};

}

#endif // TYPES_HPP